export function detectSituation(text: string): Situation {
  const t = text.toLowerCase()
  let best: Situation = 'general'
  let bestScore = 0
  for (const [s, kws] of Object.entries(keywords) as [Exclude<Situation, 'general'>, string[]][]) {
    const score = kws.reduce((a, k) => a + (t.includes(k.toLowerCase()) ? (k.length >= 3 ? 2 : 1) : 0), 0)
    if (score > bestScore) {
      best = s
      bestScore = score
    }
  }
  return best
}

