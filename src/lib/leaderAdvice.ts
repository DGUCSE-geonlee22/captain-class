const bespoke: Record<string, Bespoke> = { whitebeard, 'yi-sunsin': yiSunsin }

export function makeAdvice(leader: LeaderProfile, concern: string): Advice {
  const situation = detectSituation(concern)
  const b = bespoke[leader.id]?.[situation]
  if (b) {
    return { leaderId: leader.id, situation, opener: leader.voice.opener, read: b.read, steps: b.steps, example: b.example, closer: leader.voice.closer, reflect: b.reflect }
  }
  const tail = situationTail[situation]
  const main = leader.cases[0]
  return {
    leaderId: leader.id,
    situation,
    opener: leader.voice.opener,
    read: `${situationRead[situation]} 나는 ${leader.pillars.map((p) => p.name).slice(0, 2).join('과 ')}으로 이 상황을 보겠습니다.`,
    steps: leader.moves.map((m, i) => (i === 0 && tail ? `${m} ${tail}.` : `${m}.`)),
    example: main ? `${main.title} — ${main.desc}` : undefined,
    closer: leader.voice.closer,
    reflect: `${leader.name}의 방식 중 오늘 당장 해 볼 수 있는 한 가지는 무엇인가요?`,
  }
}
